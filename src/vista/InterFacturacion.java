    private void jButtonBuscaClienteActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButtonBuscaClienteActionPerformed
        // TODO add your handling code here:
        String ClienteBuscar = txtClienteBuscar.getText().trim();
        Connection cn = Conexion.conectar();
        String sql = "SELECT nombre, apellido FROM cliente WHERE dni = '" + ClienteBuscar + "'";
        Statement st;

        try {
            st = cn.createStatement();
            ResultSet rs = st.executeQuery(sql);

            if (rs.next()) {
                jComboBoxCliente.setSelectedItem(rs.getString("nombre") + " " + rs.getString("apellido"));

            } else {
                jComboBoxCliente.setSelectedItem("Seleccione cliente:");
                JOptionPane.showMessageDialog(null, "Dni del cliente incorrecta o no encontrada");

            }
            txtClienteBuscar.setText("");
            cn.close();

        } catch (SQLException e) {
            System.out.println("Error al buscar cliente" + e);
        }
    }//GEN-LAST:event_jButtonBuscaClienteActionPerformed

    private void jButtonAñadirProductoActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButtonAñadirProductoActionPerformed
        // TODO add your handling code here:
        String combo = this.jComboBoxProducto.getSelectedItem().toString();
        // Validar que seleccione un producto
        if (combo.equalsIgnoreCase("Seleccione producto:")) {
            JOptionPane.showMessageDialog(null, "Seleccione un Producto");
        } else {
            // Validar que ingrese una cantidad
            if (!txtCantidad.getText().isEmpty()) {
                // Validar que el usuario no ingrese caractéres no numéricos
                boolean validacion = validar(txtCantidad.getText());
                if (validacion == true) {
                    // Validar que la cantidad sea mayor a cero
                    if (Integer.parseInt(txtCantidad.getText()) > 0) {
                        cantidad = Integer.parseInt(txtCantidad.getText());
                        //ejecutar metodo para obtener datos del producto
                        this.DatosDelProducto();
                        //Validar que la cantidad de producto seleccionado no sea mayor a la base de datos
                        if (cantidad <= cantidadProductoBBDD) {

                            subtotal = precioUnitario * cantidad;
                            totalPagar = subtotal + iva + descuento;

                            // Redondear decimales
                            subtotal = (double) Math.round(subtotal * 100) / 100;
                            iva = (double) Math.round(iva * 100) / 100;
                            descuento = (double) Math.round(descuento * 100) / 100;
                            totalPagar = (double) Math.round(totalPagar * 100) / 100;

                            //Se crea un nuevo producto
                            producto = new DetalleVenta(auxIdDetalle,
                                    1,
                                    idProducto,
                                    nombre,
                                    Integer.parseInt(txtCantidad.getText()),
                                    precioUnitario,
                                    subtotal,
                                    descuento,
                                    iva,
                                    totalPagar,
                                    1);

                            // Añadir a la lista
                            listaProductos.add(producto);
                            JOptionPane.showMessageDialog(null, "Producto Agregado");
                            auxIdDetalle++;
                            txtCantidad.setText("");// Limpiar el campo
                            // Volver a cargar el combo producto

                            this.CargarComboProducto();
                            this.CalcularTotalPagar();
                            txtEfectivo.setEnabled(true);
                            jButtonCalcularCambio.setEnabled(true);

                        } else {
                            JOptionPane.showMessageDialog(null, "La cantidad supera el Stock");
                        }
                    } else {
                        JOptionPane.showMessageDialog(null, "La cantidad no puede ser 0 (cero), ni negativa");
                    }
                } else {
                    JOptionPane.showMessageDialog(null, "En la cantidad no se admiten caracteres no numéricos");
                }
            } else {
                JOptionPane.showMessageDialog(null, "Ingrese la cantidad de productos");
            }
        }
        // Llamar al método
        this.listaTablaProductos();
    }//GEN-LAST:event_jButtonAñadirProductoActionPerformed

    private void jButtonCalcularCambioActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButtonCalcularCambioActionPerformed
        // TODO add your handling code here:
        if (!txtEfectivo.getText().isEmpty()) {
            // Validamos que el usuario no ingrese otro caracteres no numéricos
            boolean validacion = validarDouble(txtEfectivo.getText());
            if (validacion == true) {
                // Validar que el efectivo sea mayor a cero(0)
                double efc = Double.parseDouble(txtEfectivo.getText().trim());
                double tpr = Double.parseDouble(txtTotalPagar.getText().trim());

                if (efc < tpr) {
                    JOptionPane.showMessageDialog(null, "El dinero en efectivo no es suficiente");
                } else {

                    double cambio = efc - tpr; // Cálculo del cambio
                    double cambi = (double) Math.round(cambio * 100d) / 100; // Redondeo a 2 decimales

// Formato para siempre mostrar dos decimales
                    DecimalFormat formato = new DecimalFormat("#.00");
                    String camb = formato.format(cambi); // Formatea el valor redondeado
                    txtCambio.setText(camb); // Muestra en el campo de texto

                }

            } else {
                JOptionPane.showMessageDialog(null, "No se admiten caracteres no numéricos");
            }
        } else {
            JOptionPane.showMessageDialog(null, "Ingrese dinero en efectivo para calcular cambio");
        }
    }//GEN-LAST:event_jButtonCalcularCambioActionPerformed
