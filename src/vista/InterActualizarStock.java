    //Metodo para cargar los productos en JComboBox
    private void cargarComboProductos() {
        Connection cn = Conexion.conectar();
        String sql = "SELECT * FROM producto";
        Statement st;
        try {
            st = cn.createStatement();
            ResultSet rs = st.executeQuery(sql);
            jComboBoxProducto.removeAllItems();
            jComboBoxProducto.addItem("Seleccione productos:");

            while (rs.next()) {
                jComboBoxProducto.addItem(rs.getString("nombre"));
            }

        } catch (SQLException e) {
            System.out.println("Error al cargar los productos en: " + e);
        }
    }

    // Metodo para mostrar stock del producto seleccionado
    private void MostrarStock() {
        try {
            Connection cn = Conexion.conectar();
            String sql = "SELECT * FROM producto WHERE nombre = '" + this.jComboBoxProducto.getSelectedItem() + "'";
            Statement st;
            st = cn.createStatement();
            ResultSet rs = st.executeQuery(sql);

            if (rs.next()) {
                idProducto = rs.getInt("idProducto");
                cantidad = rs.getInt("cantidad");
                txtCantidadActual.setText(String.valueOf(cantidad));
            } else {
                txtCantidadActual.setText("");
            }

        } catch (SQLException e) {
            System.out.println("Error al obtener stock del producto: " + e);
        }
    }
    // Metodo de validacion de caracteres no numericos

    private boolean validar(String valor) {
        int num;
        try {
            num = Integer.parseInt(valor);
            return true;
        } catch (NumberFormatException e) {
            return false;
        }
    }
