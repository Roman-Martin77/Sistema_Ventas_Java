    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        // TODO add your handling code here:

        // Validamos seleccion de producto
        if (!jComboBoxProducto.getSelectedItem().equals("Seleccione productos:")) {
            // Validamos campos vacios
            if (!txtCantidadNueva.getText().isEmpty()) {
                // Validamos que el usuario no ingrese otros caracteres no numericos
                boolean validacion = validar(txtCantidadNueva.getText().trim());
                if (validacion == true) {
                    //validamos que la cantidad sea mayor a (0)
                    if (Integer.parseInt(txtCantidadNueva.getText()) > 0) {

                        Producto producto = new Producto();
                        CtrlProducto controlProducto = new CtrlProducto();
                        int stockActual = Integer.parseInt(txtCantidadActual.getText().trim());
                        int stockNuevo = Integer.parseInt(txtCantidadNueva.getText().trim());

                        stockNuevo = stockActual + stockNuevo;
                        producto.setCantidad(stockNuevo);

                        if (controlProducto.actualizarStock(producto, idProducto)) {
                            JOptionPane.showMessageDialog(null, "Stock Actualizado");
                            jComboBoxProducto.setSelectedItem("Seleccione producto:");
                            txtCantidadActual.setText("");
                            txtCantidadNueva.setText("");
                            this.cargarComboProductos();
                        } else {
                            JOptionPane.showMessageDialog(null, "Error al actualizar");
                        }

                    } else {
                        JOptionPane.showMessageDialog(null, "La cantidad no puede ser ni cero ni negativa");
                    }

                } else {
                    JOptionPane.showMessageDialog(null, "En la cantidad no se admiten caracteres no numericos");
                }
            } else {
                JOptionPane.showMessageDialog(null, "Ingrese una nueva cantidad para sumar el stock del producto");
            }

        } else {
            JOptionPane.showMessageDialog(null, "Seleccione un producto");
        }

    }//GEN-LAST:event_jButton1ActionPerformed


