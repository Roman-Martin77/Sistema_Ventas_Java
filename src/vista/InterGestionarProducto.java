    private void jButtonActualizarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButtonActualizarActionPerformed
        // TODO add your handling code here:
        Producto producto = new Producto();
        CtrlProducto controlProducto = new CtrlProducto();
        String iva = "";
        String categoria = "";
        iva = jComboBoxIva.getSelectedItem().toString().trim();
        categoria = jComboBoxCategoria.getSelectedItem().toString().trim();

        // Validar campos
        if (txtNombre.getText().isEmpty() || txtCantidad.getText().isEmpty() || txtPrecio.getText().isEmpty()) {

            JOptionPane.showMessageDialog(null, "Complete todos los Campos");

        } else {

            if (iva.equalsIgnoreCase("Seleccione Iva:")) {
                JOptionPane.showMessageDialog(null, "Seleccione el Iva");
            } else {
                if (categoria.equalsIgnoreCase("Seleccione Categoria:")) {
                    JOptionPane.showMessageDialog(null, "Seleccione Categoria:");
                } else {
                    try {

                        producto.setNombre(txtNombre.getText().trim());
                        producto.setCantidad(Integer.parseInt(txtCantidad.getText().trim()));
                        String precioTXT = "";
                        double Precio = 0.0;
                        precioTXT = txtPrecio.getText().trim();
                        boolean aux = false;
                        // Si el usuario ingresa , (coma) como punto decimal,
                        //lo transformamos en punto (.)
                        for (int i = 0; i < precioTXT.length(); i++) {
                            if (precioTXT.charAt(i) == ',') {
                                String precioNuevo = precioTXT.replace(",", ".");
                                Precio = Double.parseDouble(precioNuevo);
                                aux = true;
                            }
                        }

                        //Evaluar la condición 
                        if (aux == true) {
                            producto.setPrecio(Precio);
                        } else {
                            Precio = Double.parseDouble(precioTXT);
                            producto.setPrecio(Precio);
                        }
                        producto.setDescripcion(txtDescripcion.getText().trim());
                        //Porcentaje IVA
                        if (iva.equalsIgnoreCase("No graba Iva")) {
                            producto.setPorcentajeIva(0);

                        } else if (iva.equalsIgnoreCase("10%")) {

                            producto.setPorcentajeIva(10);

                        } else if (iva.equalsIgnoreCase("21%")) {
                            producto.setPorcentajeIva(21);
                        }
                        //idCategoria - Cargar método que tiene el id de categoría
                        this.IdCategoria();
                        producto.setIdCategoria(obtenerIdCategoriaCombo);
                        producto.setEstado(1);

                        if (controlProducto.actualizar(producto, idProducto)) {
                            JOptionPane.showMessageDialog(null, "Registro Actualizado");

                            this.CargarComboCategoria();
                            this.cargarTablaProductos();
                            this.jComboBoxIva.setSelectedItem("Seleccione Iva:");
                            this.Limpiar();

                        } else {
                            JOptionPane.showMessageDialog(null, "Error al Actualizar");
                        }

                    } catch (HeadlessException | NumberFormatException e) {
                        System.out.println("Error en: " + e);
                    }
                }
            }

        }

    }//GEN-LAST:event_jButtonActualizarActionPerformed

