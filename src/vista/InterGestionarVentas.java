    private void jButtonActualizarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButtonActualizarActionPerformed
        // TODO add your handling code here:
        CabeceraVenta cabeceraVenta = new CabeceraVenta();
        CtrlRegistrarVenta controlRegistrarVenta = new CtrlRegistrarVenta();
        String cliente, estado;
        cliente = jComboBoxCliente.getSelectedItem().toString().trim();
        estado = jComboBoxEstado.getSelectedItem().toString().trim();

        // Metodo para obtener el id del cliente
        try {
            Connection cn = Conexion.conectar();
            PreparedStatement pst = cn.prepareStatement(
                    "SELECT idCliente, concat(nombre, ' ', apellido) AS cliente "
                    + "FROM cliente WHERE concat(nombre, ' ', apellido) = '" + cliente + "'");
            ResultSet rs = pst.executeQuery();
            if (rs.next()) {
                idCliente = rs.getInt("IdCliente");
            }
            cn.close();

        } catch (SQLException e) {
            System.out.println("Error al cargar id cliente: " + e);
        }

        // Actualizar datos
        if (!cliente.equalsIgnoreCase("Seleccione cliente:")) {
              cabeceraVenta.setIdCliente(idCliente);
              if(estado.equalsIgnoreCase("Activo")){
                  cabeceraVenta.setEstado(1);
              }else{
                  cabeceraVenta.setEstado(0);
              }
              
              if(controlRegistrarVenta.actualizar(cabeceraVenta, idVenta)){
                  JOptionPane.showMessageDialog(null, "Registro Actualizado");
                  this.cargarTablaVentas();
                  this.Limpiar();
              }else{
                  JOptionPane.showMessageDialog(null, "Error al Actualizar");
              }
        } else {
              JOptionPane.showMessageDialog(null, "Seleccione un registro para actualizar datos");
        }

    }//GEN-LAST:event_jButtonActualizarActionPerformed


