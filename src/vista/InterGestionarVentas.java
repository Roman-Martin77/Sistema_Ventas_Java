    // Metodo para mostrar todos los clientes registrados
    private void cargarTablaVentas() {
        Connection con = Conexion.conectar();
        DefaultTableModel model = new DefaultTableModel();
        String sql = "SELECT cv.idCabeceraVenta AS id, concat( c.nombre, ' ', c.apellido) AS cliente, \n"
                + "       cv.valorPagar AS total, cv.fechaVenta AS fecha, cv.estado \n"
                + "FROM cabecera_venta AS cv, cliente AS c \n"
                + "WHERE cv.idCliente = c.idCliente;";
        Statement st;

        try {
            st = con.createStatement();
            ResultSet rs = st.executeQuery(sql);
            InterGestionarVentas.jTable_ventas = new JTable(model);
            InterGestionarVentas.jScrollPane1.setViewportView(InterGestionarVentas.jTable_ventas);

            model.addColumn("N");  // ID
            model.addColumn("Cliente");
            model.addColumn("Total Pagar");
            model.addColumn("Fecha Venta");
            model.addColumn("estado");

            while (rs.next()) {

                Object fila[] = new Object[5];
                for (int i = 0; i < 5; i++) {
                    if (i == 4) {
                        String estado = String.valueOf(rs.getObject(i + 1));
                        if (estado.equalsIgnoreCase("1")) {
                            fila[i] = "Activo";
                        } else {
                            fila[i] = "Inactivo";
                        }
                    } else {
                        fila[i] = rs.getObject(i + 1);
                    }

                }
                model.addRow(fila);
            }
            con.close();

        } catch (SQLException e) {
            System.out.println("Error al llenar la tabla de ventas");
        }

        jTable_ventas.addMouseListener(new MouseAdapter() {
            @Override
            public void mouseClicked(MouseEvent e) {
                int fila_point = jTable_ventas.rowAtPoint(e.getPoint());
                int columna_point = 0;

                if (fila_point > -1) {
                    idVenta = (int) model.getValueAt(fila_point, columna_point);
                    EnviarDatosVentaSeleccionada(idVenta);//Metodo
                }
            }
        });
    }

    private void EnviarDatosVentaSeleccionada(int idVenta) {

        try {
            Connection con = Conexion.conectar();
            PreparedStatement pst = con.prepareStatement(
                    "SELECT cv.idCabeceraVenta, cv.idCliente, concat(c.nombre, ' ', c.apellido) AS cliente,  "
                    + "cv.valorPagar, cv.fechaVenta, cv.estado FROM cabecera_venta AS cv, "
                    + "cliente AS c WHERE cv.idCabeceraVenta = ' " + idVenta + "' AND cv.idCliente = c.idCliente;");
            ResultSet rs = pst.executeQuery();

            if (rs.next()) {
                jComboBoxCliente.setSelectedItem(rs.getString("cliente"));
                txtTotalPagar.setText(rs.getString("valorPagar"));
                txtFecha.setText(rs.getString("fechaVenta"));
                int estado = rs.getInt("estado");
                if (estado == 1) {
                    jComboBoxEstado.setSelectedItem("Activo");
                } else {
                    jComboBoxEstado.setSelectedItem("Inactivo");
                }

            }
            con.close();

        } catch (SQLException e) {
            System.out.println("Error al seleccionar venta");
        }
    }

    /*
     Metodo para cargar los clientes en el jComboBoxCliente
     */
    private void CargarComboClientes() {
        Connection cn = Conexion.conectar();
        String sql = "SELECT * FROM cliente";
        Statement st;

        try {
            st = cn.createStatement();
            ResultSet rs = st.executeQuery(sql);
            jComboBoxCliente.removeAllItems();
            jComboBoxCliente.addItem("Seleccione cliente:");
            while (rs.next()) {
                jComboBoxCliente.addItem(rs.getString("nombre") + " " + rs.getString("apellido"));
            }
            cn.close();

        } catch (SQLException e) {
            System.out.println("Error al cargar clientes" + e.getMessage());
        }
    }

