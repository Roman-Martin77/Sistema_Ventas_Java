    private void jButtonActualizarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButtonActualizarActionPerformed
        // TODO add your handling code here:
        if (!txtDescripcion.getText().isEmpty()) {
            Categoria categoria = new Categoria();
            CtrlCategoria controlCategoria = new CtrlCategoria();

            categoria.setDescripcion(txtDescripcion.getText().trim());
            if (controlCategoria.actualizar(categoria, idCategoria)) {
                JOptionPane.showMessageDialog(null, "Categoría Actualizada");
                txtDescripcion.setText("");
                this.cargarTablaCategorias();
            } else {
                JOptionPane.showMessageDialog(null, "Error al actualizar la categoría");
            }
        } else {
            JOptionPane.showMessageDialog(null, "Seleccione una categoría");
        }
    }//GEN-LAST:event_jButtonActualizarActionPerformed

